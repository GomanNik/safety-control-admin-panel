# Правила разметки

## Целевая модель

Тип модели:

```text
YOLO object detection
```

Модель должна находить не просто человека, а объект проверки.

## Классы

### 0. head_allowed

Голова видна, разрешенный санитарный головной убор виден достаточно хорошо.

Примеры:

* белая санитарная шапочка;
* сетка;
* колпак;
* иной разрешенный головной убор из принятого списка.

Размечаем область головы вместе с головным убором.

---

### 1. head_no_headwear

Голова видна, головного убора нет.

Размечаем область головы.

Это потенциальное нарушение.

---

### 2. head_forbidden

Голова видна, но головной убор не из разрешенного списка.

Примеры:

* обычная кепка;
* капюшон;
* шапка не санитарного типа;
* иной запрещенный вариант.

Размечаем область головы вместе с головным убором.

---

### 3. head_unknown

Голова есть, но нельзя надежно определить статус.

Причины:

* сильное размытие;
* перекрытие;
* слишком малая область;
* плохой свет;
* голова видна частично;
* головной убор неразборчив.

Важно:

```text
head_unknown не является нарушением
```

Он нужен, чтобы система честно говорила: “проверить нельзя”.

---

### 4. body_fragment_ignore

Видна часть человека, но головы нет или проверить головной убор невозможно.

Примеры:

* рука;
* перчатка;
* халат без головы;
* ноги;
* часть корпуса;
* фрагмент за печкой;
* человек сильно перекрыт оборудованием.

Это не нарушение.

Этот класс нужен, чтобы модель не путала фрагменты тела с проверяемыми головами.

## Что не размечать

Не размечаем:

* предметы кухни;
* печку;
* столы;
* стены;
* посуду;
* пустой фон.

## Главное правило

Если головной убор проверить нельзя, это не `head_no_headwear`.

Это либо:

```text
head_unknown
```

если голова хотя бы частично видна,

либо:

```text
body_fragment_ignore
```

если головы нет.
