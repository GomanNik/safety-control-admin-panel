# Headwear Detector V2

## Главная проблема

Текущий детектор человека слишком общий.

Он хорошо находит человека как объект, но для нашей задачи это вредно:

- рука может стать person bbox;
- кусок халата может стать person bbox;
- человек за печкой может создать непригодный bbox;
- трек может жить, хотя головы не видно;
- нижний край камеры может показывать только голову, но не всё тело.

Для проекта важен не сам факт наличия person bbox, а возможность проверить санитарный головной убор.

## Новая постановка

Главный объект анализа:

```text
проверяемое наблюдение головы / головного убора
````

А не:

```text
bbox человека целиком
```

## Цель эксперимента

Проверить, можно ли заменить текущую связку:

```text
универсальный детектор человека
+ crop верхней части person bbox
+ classifier головного убора
```

на одну специализированную detection-модель:

```text
детектор головы / статуса головного убора
```

Она должна за один прогон находить проверяемые объекты:

* голова в разрешенном головном уборе;
* голова без головного убора;
* запрещенный головной убор;
* неразборчивая голова;
* фрагмент тела, который нельзя проверять.

## Что не делаем на этом этапе

* не меняем рабочий runtime;
* не правим текущий person detector;
* не внедряем новую модель в проект;
* не создаем новые runtime-фильтры;
* не засоряем `vision/app`.

Этот каталог нужен только для постановки эксперимента, разметки и проверки гипотезы.
