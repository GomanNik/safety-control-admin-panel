# План оценки качества

## Что измеряем

Обычная accuracy здесь недостаточна.

Нужно проверять:

```text
качество обнаружения проверяемой головы
качество отличия головы от фрагмента тела
качество событий во времени
```

## Метрики модели

Для detection-модели:

```text
mAP по классам
precision по head_no_headwear
recall по head_no_headwear
precision по body_fragment_ignore
ошибки head_allowed → head_no_headwear
ошибки body_fragment_ignore → head_no_headwear
```

## Самые опасные ошибки

### 1. Ложное нарушение

```text
рука / халат / фрагмент тела → head_no_headwear
```

Это критическая ошибка.

### 2. Пропуск нарушения

```text
голова без шапочки → не найдена
```

Это тоже критическая ошибка.

### 3. Неверный статус

```text
разрешенная шапочка → no_headwear
```

Критично, потому что создает ложный инцидент.

## Event-level проверка

После модели нужно проверять не только кадры, но и события:

```text
создан ли инцидент там, где нарушение реально было
не создан ли инцидент там, где была шапочка / перекрытие / рука
```

## Критерий успеха первого эксперимента

Эксперимент можно считать успешным, если на тестовых фрагментах:

```text
рука у печки не становится нарушением
голова снизу кадра обнаруживается
наклон после разрешенной шапочки не создает нарушение
перекрытая голова не создает нарушение
человек без шапочки дает устойчивое событие
```

