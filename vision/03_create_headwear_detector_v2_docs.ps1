# Постановка проблемы

## Почему текущий подход ломается

Текущая система работает по схеме:

```text
person detector
→ person bbox
→ расчет области головы внутри bbox
→ classifier головного убора
→ temporal aggregation
```

Проблема в том, что person bbox не равен проверяемому человеку.

На камере 1 есть несколько типов сложных ситуаций.

## 1. Рука / фрагмент тела

YOLO может увидеть руку, халат или часть корпуса как человека.

Для обычного person detector это допустимо, потому что объект похож на часть человека.

Для нашей задачи это непригодно, потому что головной убор проверить невозможно.

## 2. Человек наклонился

Человека уже видели в разрешенной шапочке.

Потом он наклонился, голова исчезла или стала неразборчивой.

В этот момент нельзя создавать нарушение, потому что нет нового отрицательного наблюдения.

Правильное поведение:

```text
последний достоверный статус сохраняется
голова временно не видна
новый инцидент не создается
```

## 3. Голова перекрыта

Если голову закрывает объект сцены, проверка невозможна.

Правильное поведение:

```text
нет проверяемой головы
нет проверки
нет инцидента
```

## 4. Видна только голова снизу кадра

Это важный случай.

Человека целиком может быть не видно, но головной убор проверить можно.

Правильное поведение:

```text
голова видна
головной убор проверяем
person bbox не обязателен
```

## 5. Человек за печкой

Может быть виден фрагмент тела, рука или часть халата.

Правильное поведение:

```text
фрагмент тела есть
проверяемой головы нет
событие не создается
```

## Вывод

Нельзя строить систему вокруг вопроса:

```text
является ли этот person bbox хорошим?
```

Нужно строить систему вокруг вопроса:

```text
есть ли на кадре проверяемое наблюдение головы / головного убора?
```

