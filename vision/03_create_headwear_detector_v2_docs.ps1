# Алгоритм будущей обработки

## Новая логика

Было:

```text
person bbox
→ crop головы
→ classifier
```

Должно стать:

```text
детектор проверяемых голов / головных уборов
→ head observation
→ temporal logic
→ event decision
```

## Один прогон модели

На рабочем кадре вызывается одна специализированная модель.

Она возвращает:

```text
head_allowed
head_no_headwear
head_forbidden
head_unknown
body_fragment_ignore
```

## Состояние эпизода

Для каждого наблюдаемого человека или головы храним:

```text
episode_id
last_reliable_status
last_reliable_time
last_head_box
unknown_streak
missing_streak
violation_streak
allowed_streak
```

## Правила

### Разрешенный головной убор

Если пришел `head_allowed`:

```text
last_reliable_status = allowed
allowed_streak += 1
violation_streak = 0
```

Инцидент не создается.

---

### Нет головного убора

Если пришел `head_no_headwear`:

```text
violation_streak += 1
```

Инцидент создается только после устойчивого подтверждения:

```text
violation_streak >= N
```

Один кадр не является нарушением.

---

### Запрещенный головной убор

Если пришел `head_forbidden`:

```text
violation_streak += 1
```

Создание события такое же, как для отсутствия головного убора.

---

### Голова есть, но статус неизвестен

Если пришел `head_unknown`:

```text
новый статус не принимаем
инцидент не создаем
удерживаем последний достоверный статус ограниченное время
```

---

### Видна только рука / халат / фрагмент

Если пришел `body_fragment_ignore`:

```text
не проверяем
не создаем инцидент
не обновляем надежный статус
```

---

### Голова временно исчезла

Если раньше был надежный статус, а потом голова пропала:

```text
статус удерживается короткое время
новое нарушение не создается
```

Это решает случай, когда человек наклонился.

## Нижний край камеры

Если видна только голова снизу кадра:

```text
person bbox не нужен
head observation достаточно
```

Система проверяет головной убор.

## Печка / перекрытие

Если видны рука или халат за печкой:

```text
body_fragment_ignore
```

Если голова перекрыта:

```text
head_unknown или отсутствие head observation
```

Инцидент не создается.
